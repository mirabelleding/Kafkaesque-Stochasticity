BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE public.environments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_by UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.modalities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_by UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.subjects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_by UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.subject_presence (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id INTEGER NOT NULL
        REFERENCES public.subjects(id) ON DELETE CASCADE,
    presence_interval TSRANGE NOT NULL,
    created_by UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (NOT isempty(presence_interval)),
    CHECK (NOT lower_inf(presence_interval)),

    CONSTRAINT subject_presence_no_overlap
        EXCLUDE USING gist (
            subject_id WITH =,
            presence_interval WITH &&
        )
);

CREATE TABLE public.occurrences (
    uuid UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    occurred_at TIMESTAMP NOT NULL,
    environment_id INTEGER NOT NULL
        REFERENCES public.environments(id) ON DELETE RESTRICT,
    modality_id INTEGER NOT NULL
        REFERENCES public.modalities(id) ON DELETE RESTRICT,
    ka_score NUMERIC NOT NULL
        CHECK (
            (ka_score BETWEEN 1 AND 10 AND ka_score = trunc(ka_score))
            OR ka_score = 'Infinity'::NUMERIC
        ),
    subject_id INTEGER NOT NULL
        REFERENCES public.subjects(id) ON DELETE RESTRICT,
    created_by UUID NOT NULL
        REFERENCES auth.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.testimonies (
    occurrence_id UUID PRIMARY KEY
        REFERENCES public.occurrences(uuid) ON DELETE RESTRICT,
    testimony TEXT NOT NULL
        CHECK (btrim(testimony) <> '')
);

CREATE INDEX occurrences_occurred_at_idx
    ON public.occurrences (occurred_at);

CREATE INDEX occurrences_subject_occurred_at_idx
    ON public.occurrences (subject_id, occurred_at);

CREATE INDEX occurrences_created_by_idx
    ON public.occurrences (created_by);

ALTER TABLE public.environments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.modalities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subjects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subject_presence ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.occurrences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.testimonies ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE
    public.environments,
    public.modalities,
    public.subjects,
    public.subject_presence,
    public.occurrences,
    public.testimonies
FROM PUBLIC, anon, authenticated;

COMMIT;